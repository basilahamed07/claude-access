# Windows (PowerShell) equivalent of init-env.sh: write deploy/.env with fresh random secrets if it does not exist.
# Never overwrites. Run from anywhere:  powershell -ExecutionPolicy Bypass -File deploy\init-env.ps1
$ErrorActionPreference = "Stop"
$envFile = Join-Path $PSScriptRoot ".env"
if (Test-Path $envFile) { Write-Host "deploy/.env already exists; leaving it alone"; exit 0 }

$rng = [Security.Cryptography.RandomNumberGenerator]::Create()
function New-Secret {
  $b = New-Object byte[] 48; $rng.GetBytes($b)
  ([Convert]::ToBase64String($b) -replace '[^A-Za-z0-9]', '').Substring(0, 40)
}
# Fernet key: urlsafe base64 of 32 random bytes, '=' padding kept (44 chars).
$k = New-Object byte[] 32; $rng.GetBytes($k)
$fernet = [Convert]::ToBase64String($k).Replace('+', '-').Replace('/', '_')

$lines = @(
  "# Generated by deploy/init-env.ps1. Keep it secret; losing AGENTSHIELD_MASTER_KEY makes stored provider keys unreadable.",
  "POSTGRES_PASSWORD=$(New-Secret)",
  "AGENTSHIELD_APP_PASSWORD=$(New-Secret)",
  "AGENTSHIELD_WORKER_PASSWORD=$(New-Secret)",
  "AGENTSHIELD_MASTER_KEY=$fernet",
  "AGENTSHIELD_KEY_PEPPER=$(New-Secret)",
  "AGENTSHIELD_JWT_SECRET=$(New-Secret)",
  "AGENTSHIELD_SESSION_SECRET=$(New-Secret)"
)
# Like `chmod 600`: create the file empty, restrict it to the current user (by SID, so domain accounts work), and only
# then write the secrets, so there is no window in which other local users can read them.
New-Item -ItemType File -Path $envFile | Out-Null
$sid = [Security.Principal.WindowsIdentity]::GetCurrent().User.Value
& icacls.exe $envFile /inheritance:r /grant:r "*${sid}:(F)" | Out-Null
if ($LASTEXITCODE -ne 0) { Remove-Item $envFile -Force; throw "could not restrict permissions on deploy/.env" }
# ASCII without BOM and with LF endings, like the bash version.
[IO.File]::WriteAllText($envFile, ($lines -join "`n") + "`n", (New-Object Text.ASCIIEncoding))
Write-Host "wrote deploy/.env"
